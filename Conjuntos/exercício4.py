#Verificar um elemento

# frutas = {"maçã", "banana", "uva", "laranja"}
# 1. Verifique se "banana" está no conjunto.
# 2. Verifique se "morango" está no conjunto.
# 3. Use if/else para exibir uma mensagem para cada verificação.
# Conceitos: in e if/else.


#Criando o conjunto.
frutas = {"maçã", "banana", "uva", "laranja"}
#Verificando se "banana" está no conjunto
if "banana" in frutas:
    print("Morango Encontrada")
else:
    print("Fruta não encontrada")
#Verficando se morango está no conjunto.
if "morango" in frutas:
    print("Morango Encontrado")  
else:
    print("Fruta não encontrada")          
