#Adicionar e remover

# linguagens = {"Python", "Java", "C"}
# 1. Adicione "JavaScript".
# 2. Remova "Java".
# 3. Mostre o conjunto atualizado.
# 4. Mostre a quantidade de linguagens.
# Conceitos: .add(), .remove() e len().

linguagens = {"Python", "Java", "C"}
print(linguagens)
#Adcionando "JavaScript"
linguagens.add("JavaScript")
#Removendo o "Java"
linguagens.remove("Java")
#Conjunto Atualizado.
print(linguagens)
#Quantidade de Linguagens
print(len(linguagens))

