#Média de notas
#Peça duas notas e calcule a média.
#Fórmula:
# Média = n1 + n2 / 2
#Depois mostre o resultado.

print("Media das Notas")

num1 = float(input("Digite sua primeira nota: "))
num2 = float(input("Digite sua segunda nota: "))

media = (num1 + num2) / 2

print(f"Sua Média final é:  {media}")