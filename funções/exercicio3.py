# Dobro de um número
# Crie uma função dobro(numero) que receba um número e retorne o dobro dele.
# Exemplo:
# resultado = dobro(8)print(resultado)


# Resultado:
# 16


def dobro(numero):
    return numero * 2

numero = int(input("Digite um numero: "))
resultado = dobro(numero)
print(f"O dobro do seu numero é: {resultado}")

   