# Crie quatro funções:
# somar(a, b)subtrair(a, b)multiplicar(a, b)dividir(a, b)


# Cada função deve receber dois números e retornar o resultado.
# Depois faça:
# print(somar(10, 5))print(subtrair(10, 5))print(multiplicar(10, 5))print(dividir(10, 5))
#função para somar números:
def somar(a, b):
    return a + b

print(somar(10, 5))


#Função para subtrair numeros:
def subtrair(a, b):
    return a - b

print(subtrair(10, 7))


#Função para multiplicar números:
def multiplicar(a, b):
    return a * b

print(multiplicar(12, 7))



#Função para dividir números:
def dividir(a, b):
    return a / b

print(dividir(24, 6))

    