# Soma de dois números
# Peça dois números ao usuário e mostre:
#soma
#subtração
#multiplicação
#divisão
num1 = float(input("Digite seu primeiro numero: "))
num2 = float(input("Digite seu segundo numero: "))

soma = num1 + num2
subtracao = num1 - num2
multiplicacao = num1 * num2
divisao = num1 / num2

print(soma)
print(subtracao)
print(multiplicacao)
print(divisao)